      For centuries, technology and finance have lived in simpatico, hand in glove relationship. Money, for instance, was one of the initial financial technologies. Salt bars, known commonly as amoles, were once used as a financial technology for centuries in Ethiopia. And by simply allowing you to attach money to a telegram, the telegram rapidly changed many parts of the financial sector in the late 19th Century.
    </p>

    <p>
      But as you would guess, I am not about to go on for the rest of this article pitching a salt currency (however much I would love that), and it's fair to say that a telegram, if you even know what that is, is not the first thing that comes to your mind when a bee buzzes "Fintech" in your ear. So in line with that, what we really mean by Fintech is the cutting edge stuff, the game changing ideas. Or to put it more eloquently:
    </p>

    <blockquote>
      "… technology-enabled innovations in financial services associated with new business models, applications, processes, or products, all of which have a material effect…"
    </blockquote>

