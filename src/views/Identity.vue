    </p>

    <p>
      It's a tough one, right? But what we can draw from this is that both the bank and insurance companies want to give their users a streamlined, seamless one stop experience. The customer interface.
    </p>

    <h2>The Friction of Innovation</h2>
    <p>
      Let's look at a common scenario.
    </p>

    <p>
      You're building a software company solving problems for ride sharing in Zimbabwe, say Uber Zimbabwe. You've spent many hours building a complex integration with a payment processing platform. The integration allows your customer (the passenger) to handle online and in-person transactions directly through their app (as a redirect from your app). It's also how the drivers get paid. As the ride sharing businesses grow, you receive frequent requests from their customers and drivers to mention their own ideas for improvements they'd like to see in your platform.
    </p>

    <p>
      Everyone wants optionality for how they send and receive money: Mobile money, Same Day Fast transfer, RTP, push-to-debit, pre-paid cards, coupons, Zipit, and a host of other third-party integrations. As the lead innovator, you may think these requests seem trivial. But at this point, it doesn't even matter. You have no say in the roadmap of your legacy payment processor.
    </p>

    <p>
      Even if you decided to bring the payments experience in-house, you would now be spending valuable time and energy trying to orchestrate third-party payments versus executing on your mission to make ride sharing simpler for car owners and customers. What does it even mean to bring payments in-house? How do you scope the effort? Should you get on the phone with technical resources from your company's bank? Search for payment APIs?
    </p>

    <p>
      It's daunting to know where to begin, but it shouldn't be. You shouldn't have to spend months figuring out how to build payment technology, manage risk and compliance, and become a payments guru. That's not the business you set out to create.
    </p>

    <h2>The Shift to Embedded Finance</h2>
    <p>
      And by that logic, a payment processor shouldn't have to spend much effort trying to build this ride-sharing app.
    </p>

    <p>
      The future of African fintech lies in abstraction. The veteran teams who know the banking system and deeply understand payment infrastructure—the maze of acquisitions, shallow APIs with horrible documentation, and regulatory complexities—will build the rails.
    </p>

    <p>
      And the product innovators—who know the ride sharing business in and out, maybe way better than any payment processor ever could—will build on top.
    </p>

    <p>
      What is needed is something bigger than banking-as-a-service. It's a movement towards connecting people to payment networks by making it easy for developers to accept, store, and disburse money. Period. Everything underneath should be abstracted away, from secure data collection to utilizing multiple payment methods with one API and leveraging new ways to monetize products.
    </p>

    <h2>Building an Ecosystem of Innovation</h2>
    <p>
      We are moving towards a network, an ecosystem of innovators, startups, and developers. The mission is to help companies keep doing what they're best at, changing the world with new and innovative software experiences, not becoming payment experts. We believe this ecosystem of continuous innovation guarantees that new technologies will regularly and frequently appear in the marketplace. Competition among technology producers will likely yield a market with multiple technologies to meet the same need in a society, thus providing a range of technology choices for the masses. Surely cost, quality, and reliability will be among the technology features that can make these innovations pro poor.
    </p>

    <p>
      Through an ecosystem of organizations leveraging this technology, we enable the simple creation of next generation financial products, services, innovations and exchange of value across industries financial institutions and government institutions.
    </p>

    <p>
      This model is in contrast to payment processors building a moat around their APIs, and attempting to make innovations in all areas. Think of a Mobile money company attempting to build a marketplace, a ride sharing app, learning management system, and a whole series of worse than mediocre products, whilst making it extremely difficult for startups to use their core API.
    </p>

    <p>
      The future belongs to "outsourcing" and distributing the thinking and innovations to thousands of clever, smart, and creative geniuses all over the continent by giving them the Fintech tools they need to launch with speed using embedded payments. To allow all businesses from street vendors to large companies to have a whole basket of payment options leveraging the tools they have without having to invest in high cost devices.
    </p>

    <p>
      We are moving towards payment platforms for platform builders.
    </p>

