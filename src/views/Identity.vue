      What's interesting though is that the technology choices and the potential impact of each of these choices differs from area to area, industry to industry, partly due to occupational factors, personal preferences or purely technological concerns. Generally, the views of different technology choices are cast as either technological determinism, or social constructivism, and materialism (physical causes Drive human action) or idealism (ideas and beliefs Drive human action).
    </p>

    <h2>Social Constructivism in African Fintech</h2>
    <p>
      For social constructivism (local roles, patterns of use, and consequences that are particular to individuals), one such feature will be the role this technology will play in society. The notion that for a technology to be disruptive, it also has to be intelligently and actively responsive to the needs, interests and desires of a particular society.
    </p>

    <p>
      In other words, there is no one silver bullet to Fintech, and maybe there is no bullet at all, but a conscious set of technology choices that fuel sustainable growth.
    </p>

    <p>
      A more muted interpretation will be to say that for this tech to inspire sustainable growth in a society, it also has to be pro poor. Think of Tiered KYC, Open and interoperable systems, Open Banking, Open API, real time clearing, push payment model, same day settlement, etc.
    </p>

    <h2>The Ecosystem for Makers</h2>
    <p>
      To achieve scale, these systems need to be pro startup, and pro developer. They should be made for makers, disrupters, innovators, and solution providers. The creators building products that can change the world in many circle, reduce the economic gap, and inspire change.
    </p>

    <p>
      Creators want a better user experience for their users. They want the experience we have all come to expect from Google (Elasticsearch).
    </p>

